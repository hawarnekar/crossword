function normalise(raw, subject) {
  return raw.map(([word, topic, subtopic, hints]) => ({
    word: word.toUpperCase(),
    subject,
    topic,
    subtopic,
    hints: hints.map(([level, text]) => ({ level, text })),
  }));
}

